"""Writes src/words_table.zig, the letter table of tilla.md (Words), to stdout.

Run by hand when the table changes, never at build time:
    python3 tools/words_table.py > src/words_table.zig && zig fmt src/words_table.zig
"""
import re
import unicodedata

# Letters that don't decompose to ASCII, by the core of their Unicode name.
HAND = {
    'ETH': 'd', 'THORN': 'th', 'SHARP S': 'ss', 'DOTLESS I': 'i', 'DOTLESS J': 'j', 'KRA': 'k',
    'ENG': 'n', 'LONG S': 's', 'TONE SIX': 'b', 'TONE TWO': 's', 'TONE FIVE': 's', 'TWO': 'z',
    'DELTA': 'd', 'SCHWA': 'e', 'GAMMA': 'g', 'HWAIR': 'hv', 'IOTA': 'i', 'LAMBDA': 'l',
    'YR': 'r', 'ESH': 's', 'UPSILON': 'u', 'EZH': 'z', 'GLOTTAL STOP': 'q', 'WYNN': 'w',
    'DENTAL CLICK': 'c', 'LATERAL CLICK': 'x', 'ALVEOLAR CLICK': 'q', 'RETROFLEX CLICK': 'q',
    'YOGH': 'y',
}


def replacement(cp):
    c = chr(cp)
    s = ''.join(ch for ch in unicodedata.normalize('NFD', c) if not unicodedata.combining(ch)).lower()
    if s.isascii() and s.isalpha():
        return s
    name = unicodedata.name(c).replace(' WITH SMALL LETTER ', '')
    name = re.sub(r'^LATIN (CAPITAL |SMALL )?(LETTER|LIGATURE) ((SMALL|TURNED|REVERSED|OPEN|AFRICAN|INVERTED) )*', '', name)
    name = re.sub(r' (WITH|PRECEDED|DIGRAPH|BAR|REVERSED|LOOP)\b.*', '', name)
    return HAND.get(name, name.lower())


print('//! Generated by tools/words_table.py from Python unicodedata. Do not edit.')
print('')
print('/// The normalization of the letter U+00C0 + i; "" for × and ÷, which aren\'t letters.')
print('pub const table = [_][]const u8{')
for cp in range(0xC0, 0x250):
    r = '' if cp in (0xD7, 0xF7) else replacement(cp)
    assert r == '' or re.fullmatch('[a-z]+', r), (hex(cp), r)
    print(f'    "{r}", // U+{cp:04X} {chr(cp)}')
print('};')
